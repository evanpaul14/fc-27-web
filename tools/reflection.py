"""Dump Frostbite reflection (TypeInfoData records) from a relocated image.

Needs OUT/relocs.npy from tools/analyze.py. Record layout (empirical, FB 2025.1):
  +0x00 name*         +0x08 u32 hash, u16 flags, u16 size   +0x10 GUID
  +0x20 module*       +0x28 TypeInfo* (runtime object, bss)  +0x30 u16 align, u16 nfields, ...
  +0x38 super TypeInfo* (classes)                            +0x40 FieldInfoData[] (classes)
FieldInfoData (0x20): name*, u32 hash, u32 flags, u64 offset, TypeInfo* type.

usage: python3 -I tools/reflection.py extracted/code/main extracted/analysis/main
writes OUT/types.tsv, OUT/fields.tsv and OUT/fb_types.h
"""
import json, os, re, struct, sys
import numpy as np

IDENT = re.compile(rb'^[A-Za-z_][A-Za-z0-9_:<>,\- ]{0,200}$')


def main():
    prefix, out = sys.argv[1], sys.argv[2]
    info = json.load(open(prefix + '.json'))
    img = open(prefix + '.bin', 'rb').read()
    segs = {s['name']: s for s in info['segments']}
    ro0 = segs['ro']['mem_off']; ro1 = ro0 + segs['ro']['size']
    bss0 = segs['data']['mem_off'] + segs['data']['size']
    bss1 = bss0 + info['bss_size']
    sl = np.load(os.path.join(out, 'relocs.npy'))
    slot = dict(zip(sl[:, 0].tolist(), sl[:, 1].tolist()))

    def q(a):
        return struct.unpack_from('<Q', img, a)[0]

    scache = {}

    def name_at(a):
        if a in scache:
            return scache[a]
        r = None
        if ro0 <= a < ro1:
            e = img.find(b'\0', a, a + 256)
            t = img[a:e]
            if e > a and IDENT.match(t):
                r = t.decode()
        scache[a] = r
        return r

    def fields_at(p):
        if not p or p not in slot:
            return None
        out = []
        while True:
            n = q(p)
            if n == 0:
                return out
            nm = name_at(n) if p in slot else None
            t = q(p + 0x18)
            if nm is None or not (bss0 <= t < bss1):
                return None if not out else out
            h, fl = struct.unpack_from('<II', img, p + 8)
            out.append((nm, h, fl, q(p + 0x10), t))
            p += 0x20

    types = {}  # record addr -> dict
    for a, v in slot.items():
        nm = name_at(v)
        if nm is None or a + 0x28 not in slot:
            continue
        rt = q(a + 0x28)
        if not (bss0 <= rt < bss1):
            continue
        h, fl, size = struct.unpack_from('<IHH', img, a + 8)
        # FieldInfoData/argument arrays also match the name/+0x28 pattern but have
        # no flags, size or module pointer.
        if (fl == 0 and size == 0) or a + 0x20 not in slot:
            continue
        align, nf = struct.unpack_from('<HH', img, a + 0x30)
        sup = q(a + 0x38) if a + 0x38 in slot else 0
        rec = dict(addr=a, name=nm, hash=h, flags=fl, size=size, align=align, nfields=nf,
                   guid=img[a + 0x10:a + 0x20].hex(), module=q(a + 0x20) if a + 0x20 in slot else 0,
                   rt=rt, super=sup if bss0 <= sup < bss1 else 0,
                   fields=fields_at(q(a + 0x40)) if a + 0x40 in slot else None)
        types[a] = rec

    by_rt = {}
    for r in types.values():
        by_rt.setdefault(r['rt'], r)
    tname = lambda rt: by_rt[rt]['name'] if rt in by_rt else f'T_{rt:x}'

    # Flags bits 4..8 look like the type kind; report the distribution so it can be named.
    kinds = {}
    for r in types.values():
        k = (r['flags'] >> 4) & 0x1F
        kinds.setdefault(k, []).append(r['name'])

    with open(os.path.join(out, 'types.tsv'), 'w') as o:
        o.write('record\truntime\tname\tkind\tflags\tsize\talign\tnfields\tsuper\thash\tguid\n')
        for r in sorted(types.values(), key=lambda r: r['name']):
            o.write(f"{r['addr']:#x}\t{r['rt']:#x}\t{r['name']}\t{(r['flags'] >> 4) & 0x1F}\t{r['flags']:#06x}\t"
                    f"{r['size']}\t{r['align']}\t{r['nfields']}\t{tname(r['super']) if r['super'] else ''}\t"
                    f"{r['hash']:#010x}\t{r['guid']}\n")
    nfield = 0
    with open(os.path.join(out, 'fields.tsv'), 'w') as o, open(os.path.join(out, 'fb_types.h'), 'w') as h:
        h.write('// Generated by tools/reflection.py from Frostbite TypeInfoData. Do not edit.\n\n')
        for r in sorted(types.values(), key=lambda r: r['name']):
            if not r['fields']:
                continue
            sup = f" : public {tname(r['super'])}" if r['super'] else ''
            h.write(f"// size {r['size']:#x} align {r['align']}  typeinfo {r['rt']:#x}\n")
            h.write(f"struct {r['name']}{sup} {{\n")
            for nm, fh, fl, off, t in sorted(r['fields'], key=lambda f: f[3]):
                o.write(f"{r['name']}\t{nm}\t{off:#x}\t{tname(t)}\t{fl:#x}\t{fh:#010x}\n")
                h.write(f"    /* {off:#06x} */ {tname(t)} {nm};\n")
                nfield += 1
            h.write('};\n\n')
    summary = dict(n_types=len(types), n_unique_runtime=len(by_rt),
                   n_with_fields=sum(1 for r in types.values() if r['fields']), n_fields=nfield,
                   kinds={k: (len(v), v[:6]) for k, v in sorted(kinds.items())},
                   unresolved_field_types=len({f[4] for r in types.values() if r['fields']
                                               for f in r['fields'] if f[4] not in by_rt}))
    json.dump(summary, open(os.path.join(out, 'reflection.json'), 'w'), indent=1)
    print(json.dumps(summary, indent=1))


if __name__ == '__main__':
    main()
